#!/usr/bin/env python3
"""Render the launcher header's title lettering to alpha-mask PNGs and a C header.

The launchers (Mac, Windows, Linux) draw three strings in Star Trek title fonts:

  "Star Trek: Voyager"  Jefferies    (tinted with the secondary text colour)
  "Elite Force"         Jefferies    (tinted with the primary text colour)
  "AwayTeamEF"          TNG Credits  (tinted gold)

The fonts may not be redistributed, so they are never part of the repository or of a
build. This script renders the strings once from the user's own copies; the outputs are
committed and the builds use only those:

  tools/launcher-titles/png/<name>.png       white glyphs on transparent, trimmed to the ink,
                                             at 3x the size the launchers draw them
  EFAndroid-SP/app/jni/efcode/sys/launcher_titles.h
                                             the same PNGs as C arrays, plus each image's size
                                             and baseline in points (1x)

The launchers tint the mask with the current theme colour at runtime (so the lettering
follows light/dark mode) and scale it to the screen's pixel density.

Jefferies draws lowercase letters as small capitals: that is the font's design and is kept.
TNG Credits has only a Mac Roman character map
(asked for as encoding "armn"); every character used here is plain ASCII, the same in Mac Roman.

Usage (needs Pillow):
  python3 tools/launcher-titles/render_titles.py <folder with Jefferies.ttf and TNG_Credits.ttf>
"""
import io
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SCALE = 3          # pixels per point in the committed images
# name, text, font file, cap height in points (the height of a capital letter, which is
# what the launchers' old system-font labels are matched against: 12 pt semibold has a
# cap height of about 8.5 pt, 24 pt bold about 17 pt; Jefferies is a wide face, so
# "Elite Force" is a little smaller to leave the header room for the update notice)
TITLES = [
    ("star_trek_voyager", "Star Trek: Voyager", "Jefferies.ttf", 9.0),
    ("elite_force", "Elite Force", "Jefferies.ttf", 16.0),
    ("away_team_ef", "AwayTeamEF", "TNG_Credits.ttf", 16.0),
]

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PNG_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "png")
HEADER = os.path.join(ROOT, "EFAndroid-SP", "app", "jni", "efcode", "sys", "launcher_titles.h")


def load_font(path, size):
    # TNG Credits has only a Mac Roman character map: ask for it by name
    enc = "armn" if os.path.basename(path) == "TNG_Credits.ttf" else ""
    return ImageFont.truetype(path, size, encoding=enc)


def check_glyphs(path, text):
    """Every character must map to a glyph of the font (no silent fallback)."""
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        return
    cmap = {}
    for t in TTFont(path)["cmap"].tables:
        cmap.update(t.cmap)
    missing = sorted({c for c in text if ord(c) not in cmap})
    if missing:
        sys.exit("%s has no glyph for %r" % (os.path.basename(path), "".join(missing)))


def ink_box(font, text):
    """The ink's box of text drawn with its baseline at (0, 0): (left, top, right, bottom)."""
    img = Image.new("L", (1, 1))
    return ImageDraw.Draw(img).textbbox((0, 0), text, font=font, anchor="ls")


def render(path, text, cap_pt):
    check_glyphs(path, text)
    want = cap_pt * SCALE
    # find the font size whose capital "E" is want pixels tall (E has a flat top and bottom)
    size = 100
    for _ in range(4):
        l, t, r, b = ink_box(load_font(path, size), "E")
        size = max(4, int(round(size * want / float(b - t))))
    font = load_font(path, size)
    l, t, r, b = ink_box(font, text)
    pad = 4
    w, h = r - l + 2 * pad, b - t + 2 * pad
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).text((pad - l, pad - t), text, font=font, fill=255, anchor="ls")
    box = mask.getbbox()
    mask = mask.crop(box)
    baseline = (pad - t) - box[1]          # rows from the image's top to the baseline
    img = Image.new("RGBA", mask.size, (255, 255, 255, 0))
    img.putalpha(mask)
    return img, baseline


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("\t" + "".join("0x%02x," % b for b in data[i:i + 20]))
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    fonts = sys.argv[1]
    os.makedirs(PNG_DIR, exist_ok=True)
    out = [
        "/* Generated by tools/launcher-titles/render_titles.py: do not edit.",
        "   The launcher header's title lettering as alpha masks (white on transparent PNG),",
        "   rendered at %d pixels per point. Sizes and the baseline (rows from the top) are" % SCALE,
        "   in points; the launchers tint the mask with a theme colour. */",
        "",
        "#ifndef LAUNCHER_TITLES_H",
        "#define LAUNCHER_TITLES_H",
        "",
        "#define LT_SCALE %d" % SCALE,
        "",
        "typedef struct { const char *text; const unsigned char *png; unsigned int pngLen;",
        "\tint pxW, pxH, pxBaseline; double w, h, baseline; } launcherTitle_t;",
        "",
        "enum { LT_STAR_TREK_VOYAGER, LT_ELITE_FORCE, LT_AWAY_TEAM_EF, LT_COUNT };",
        "",
        "/* define LAUNCHER_TITLES_TYPES_ONLY for the types alone (the data is in one file) */",
        "#ifndef LAUNCHER_TITLES_TYPES_ONLY",
        "",
    ]
    entries = []
    for name, text, fontfile, cap in TITLES:
        img, baseline = render(os.path.join(fonts, fontfile), text, cap)
        buf = io.BytesIO()
        img.save(buf, "PNG", optimize=True)
        data = buf.getvalue()
        with open(os.path.join(PNG_DIR, name + ".png"), "wb") as f:
            f.write(data)
        out.append(c_array("lt_png_" + name, data))
        w, h = img.size
        entries.append('\t{ "%s", lt_png_%s, %d, %d, %d, %d, %.4f, %.4f, %.4f },' % (
            text, name, len(data), w, h, baseline, w / float(SCALE), h / float(SCALE), baseline / float(SCALE)))
        print("%-20s %4dx%-3d baseline %3d  (%.1f x %.1f pt)  %d bytes" % (text, w, h, baseline,
            w / float(SCALE), h / float(SCALE), len(data)))
    out += [
        "static const launcherTitle_t launcherTitles[LT_COUNT] = {",
    ] + entries + [
        "};",
        "",
        "#endif /* LAUNCHER_TITLES_TYPES_ONLY */",
        "",
        "#endif",
        "",
    ]
    with open(HEADER, "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(HEADER, ROOT), "and", os.path.relpath(PNG_DIR, ROOT))


if __name__ == "__main__":
    main()
